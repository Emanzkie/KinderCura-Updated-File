// /statement?appointmentId=N  — Statement of Account
// /statement?receipt=REF      — receipt for one confirmed payment
// Read-only; the server checks that the signed-in user may see the appointment.
(function () {
    if (!requireAuth()) return;

    const sheet = document.getElementById('sheet');
    const params = new URLSearchParams(location.search);

    const esc = (v) => String(v ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
    const money = (v) => `₱${(Number(v) || 0).toLocaleString('en-PH', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
    const when = (v, opts) => {
        const d = v ? new Date(v) : null;
        return d && !Number.isNaN(d.getTime()) ? d.toLocaleString('en-PH', { timeZone: 'Asia/Manila', ...opts }) : '—';
    };
    // Appointment dates are stored as a UTC calendar day, shown so on every page.
    const apptDay = (v) => when(v, { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' });
    const day = (v) => when(v, { year: 'numeric', month: 'long', day: 'numeric' });
    const dayTime = (v) => when(v, { year: 'numeric', month: 'short', day: 'numeric', hour: 'numeric', minute: '2-digit' });
    const clock = (v) => {
        const m = /^(\d{1,2}):(\d{2})$/.exec(v || '');
        return m ? `${Number(m[1]) % 12 || 12}:${m[2]} ${Number(m[1]) >= 12 ? 'PM' : 'AM'}` : (v || '—');
    };
    const title = (v) => String(v || '—').replace(/^./, (c) => c.toUpperCase());

    const head = (clinic, name) => `
        <header class="soa-head">
            <h1>${esc(clinic?.clinicName || 'KinderCura')}</h1>
            ${clinic?.address ? `<p>${esc(clinic.address)}</p>` : ''}
            ${clinic?.phoneNumber ? `<p>${esc(clinic.phoneNumber)}</p>` : ''}
        </header>
        <h2 class="soa-title">${name}</h2>`;
    const fields = (pairs) => `<dl class="soa-fields">${pairs.map(([k, v]) => `<div><dt>${k}</dt><dd>${esc(v)}</dd></div>`).join('')}</dl>`;
    const footer = () => `
        <div class="soa-sign"><span>Authorized signature</span></div>
        <p class="soa-note">Issued ${esc(dayTime(new Date()))}. Generated by KinderCura from recorded payments.</p>`;

    function statementHtml(s) {
        const rows = s.payments.map((p) => {
            const ref = p.receiptNumber || p.reference;
            return `<tr>
                <td>${esc(dayTime(p.date))}</td>
                <td>${esc(ref || '—')}${ref ? ` <a class="soa-receipt-link" href="/statement?receipt=${encodeURIComponent(ref)}" target="_blank" rel="noopener">Receipt</a>` : ''}</td>
                <td>${esc(p.method)}</td>
                <td>${p.refunded ? 'Refunded' : esc(p.type || 'Payment')}</td>
                <td class="num">${money(p.amount)}</td>
                <td class="num">${p.balanceAfter == null ? '—' : money(p.balanceAfter)}</td>
            </tr>`;
        }).join('') || '<tr><td colspan="6">No payments received.</td></tr>';

        return `${head(s.issuer, 'Statement of Account')}
            ${fields([
                ['SOA No.', s.statementNumber], ['Date issued', day(new Date())],
                ['Child', s.childName], ['Parent/Guardian', s.parentName],
                ['Pediatrician', s.pediatricianName], ['Appointment No.', `#${s.appointmentId}`],
                ['Date', apptDay(s.appointmentDate)], ['Time', clock(s.appointmentTime)],
                ['Service', s.service], ['Appointment status', title(s.appointmentStatus)],
            ])}
            <div class="soa-table-wrap"><table class="soa-table">
                <thead><tr><th>Date paid</th><th>Receipt / Reference</th><th>Method</th><th>Type</th><th class="num">Amount</th><th class="num">Balance</th></tr></thead>
                <tbody>${rows}</tbody>
            </table></div>
            <table class="soa-totals"><tbody>
                <tr><th>Consultation fee</th><td>${money(s.totalAmount)}</td></tr>
                <tr><th>Total payments received</th><td>${money(s.totalPaid)}</td></tr>
                ${s.totalRefunded > 0 ? `<tr><th>Refunded</th><td>${money(s.totalRefunded)}</td></tr>` : ''}
                <tr class="due"><th>Remaining balance</th><td>${money(s.balanceDue)}</td></tr>
                <tr><th>Payment status</th><td>${esc(s.status)}</td></tr>
            </tbody></table>
            ${s.closed ? `<p class="soa-note">This appointment was ${esc(s.appointmentStatus)}, so no balance is due.</p>` : ''}
            ${s.totalRefunded > 0 ? '<p class="soa-note">Refunded payments are listed for reference and are not counted as received.</p>' : ''}
            ${footer()}`;
    }

    function receiptHtml(r) {
        return `${head(r.issuer, 'Payment Receipt')}
            ${fields([
                ['Receipt No.', r.receiptNumber || r.paymentRef || '—'], ['Payment reference', r.paymentRef || '—'],
                ['Child', r.childName], ['Parent/Guardian', r.parentName],
                ['Pediatrician', r.pediatricianName], ['Appointment No.', r.appointmentId != null ? `#${r.appointmentId}` : '—'],
                ['Appointment date', apptDay(r.appointmentDate)], ['Appointment time', clock(r.appointmentTime)],
                ['Service', r.service], ['Date paid', dayTime(r.paidAt)],
                ['Payment method', r.paymentMethodLabel], ['Payment type', r.paymentTypeLabel],
            ])}
            <table class="soa-totals"><tbody>
                <tr><th>Consultation fee</th><td>${money(r.totalAmount)}</td></tr>
                <tr class="due"><th>Amount paid</th><td>${money(r.amount)}</td></tr>
                <tr><th>Balance after this payment</th><td>${money(r.balanceDue)}</td></tr>
                ${r.status === 'Refunded' ? '<tr><th>Status</th><td>Refunded</td></tr>' : ''}
            </tbody></table>
            ${footer()}`;
    }

    async function load() {
        const receipt = params.get('receipt');
        const appointmentId = params.get('appointmentId');
        try {
            if (receipt) {
                const data = await apiFetch(`/payments/ref/${encodeURIComponent(receipt)}/receipt`);
                document.title = `Receipt ${data.receipt.receiptNumber || data.receipt.paymentRef || ''} - KinderCura`;
                sheet.innerHTML = receiptHtml(data.receipt);
            } else if (/^\d+$/.test(appointmentId || '')) {
                const data = await apiFetch(`/payments/appointments/${appointmentId}/statement`);
                document.title = `${data.statement.statementNumber} - KinderCura`;
                sheet.innerHTML = statementHtml(data.statement);
            } else {
                throw new Error('No appointment or receipt was selected.');
            }
            document.getElementById('printBtn').hidden = false;
        } catch (err) {
            sheet.innerHTML = `<p>${esc(err.message || 'Could not load this document.')}</p>`;
        }
    }
    load();
})();
